impl DurableOutboxRetention for PgOutbox {
    /// 业务作用：通过后端中立合同执行 PostgreSQL 有界归档与保留清理轮次。
    ///
    /// 参数说明：
    /// - `policy`：冻结保留策略。
    /// - `archive`：需要收据时提供的幂等归档端。
    /// - `now_ms`：统一 epoch 毫秒时钟。
    ///
    /// 返回：只包含已确认提交事实的报告；策略或存储失败返回错误。
    async fn retention_round(
        &self,
        policy: &OutboxRetentionPolicy,
        archive: Option<&(dyn OutboxArchive + Sync)>,
        now_ms: i64,
    ) -> Result<RetentionRoundReport, OutboxStoreError> {
        PgOutbox::retention_round(self, policy, archive, now_ms).await
    }
}

impl DurableOutboxWakeup for PgOutbox {
    /// 业务作用：通过后端中立合同订阅 PostgreSQL 已确认提交代际。
    ///
    /// 参数说明：
    /// - `channel`：指定 lane 时隔离唤醒；未指定时订阅当前 datasource 的全局代际。
    ///
    /// 返回：当前进程共享的 watch 接收端；数据库轮询仍承担最终收敛。
    fn subscribe_committed_appends(&self, channel: Option<&str>) -> watch::Receiver<u64> {
        PgOutbox::subscribe_committed_appends(self, channel)
    }
}
