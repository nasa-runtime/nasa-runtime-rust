//!
//! 写侧复用 `natx-pgsql` ambient transaction；投递侧通过数据库 owner 租约与 fencing token
//! 约束 global/lane 权威，并以 `FOR UPDATE SKIP LOCKED` 按 `id` 升序领取。发布成功只确认精确前缀，
//! 取消或结果不确定保留至少一次重投语义。

