/// 业务作用：校验公开事件字段能按 MySQL/PostgreSQL 公共字节边界无损持久化。
///
/// 参数说明：
/// - `event`：待进入持久 Outbox 的事件。
///
/// 返回：身份、路由字段与 trace context 合法时成功；否则在数据库 I/O 前返回脱敏错误。
fn validate_event(event: &OutboxEvent) -> Result<(), OutboxStoreError> {
    for value in [
        (&event.event_id, 128_usize),
        (&event.aggregate_type, 128),
        (&event.aggregate_id, 190),
        (&event.event_type, 128),
    ] {
        if value.0.is_empty() || value.0.len() > value.1 || value.0.contains('\0') {
            return Err(OutboxStoreError::new("invalid outbox event identity"));
        }
    }
    if event
        .traceparent
        .as_ref()
        .is_some_and(|value| value.is_empty() || value.len() > 64 || value.contains('\0'))
    {
        return Err(OutboxStoreError::new("invalid outbox trace context"));
    }
    Ok(())
}

/// 业务作用：校验租户身份符合受信写入上下文的公共边界。
///
/// 参数说明：
/// - `tenant`：待查询或对账的受信租户身份。
///
/// 返回：身份合法时成功；否则在数据库 I/O 前返回脱敏错误。
fn validate_tenant(tenant: &str) -> Result<(), OutboxStoreError> {
    OutboxWriteContext::new(tenant.to_string())
        .map(|_| ())
        .map_err(|_| OutboxStoreError::new("invalid outbox tenant"))
}

/// 业务作用：构造未取得 owner 时的稳定空投递报告。
