//! 固定逻辑指标目录；目录声明不代表对应执行路线已经发生。

/// 指标累加或瞬时采样类型。
#[derive(Clone, Copy, Debug, PartialEq, Eq, serde::Serialize)]
pub enum MetricKind {
    /// 事件增量，由接收后端累加；复用后端与相同标签时不会自动清零。
    Counter,
    /// 最近一次独立采样，不构成业务控制权威。
    Gauge,
}
/// 两端共享的逻辑名、单位和完整低基数标签合同。
#[derive(Clone, Copy, Debug, serde::Serialize)]
pub struct MetricDefinition {
    /// 固定逻辑名称。
    pub name: &'static str,
    /// 累加或瞬时采样类型。
    pub kind: MetricKind,
    /// 逻辑单位；空串表示无量纲计数或状态。
    pub unit: &'static str,
    /// 值的业务含义与适用边界。
    pub description: &'static str,
    /// 有序标签，必含source；不接纳offset、业务key或异常文本。
    pub labels: &'static [&'static str],
}
